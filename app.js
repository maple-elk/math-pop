// Math & Logic Studio — Modular Script Notice
// 
// The application code and datasets have been modularized under the js/ directory:
//   - js/storage.js             : LocalStorage and safe storage fallback wrapper
//   - js/audio.js               : Web Audio API synthesizer, chime/pop sounds, confetti animation
//   - js/speech.js              : Web Speech API text-to-speech assistant
//   - js/data/math-data.js      : Grade topics, finite number sense sets, and math generators
//   - js/data/logic-data.js     : Isometric 3D cube renderer, logic riddles, visual and spatial slides
//   - js/data/science-data.js   : Science lab experiments and simulations
//   - js/data/preschool-data.js : Preschool patterns, counting 1-5, shapes, sizes, and sorting sets
//   - js/data/kindergarten-data.js : Kindergarten math, nature, riddles, and shapes problem sets
//   - js/app.js                 : Core UI controller, navigation, profile manager, and event wiring
//
// index.html loads these modular scripts directly for fast, buildless execution.
